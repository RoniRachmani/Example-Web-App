// Copies every key in back-end/.env into one 1Password item and rewrites
// .env.tpl with op:// references to it, so .env can be rebuilt with
// `npm run env:pull`. Run again after adding, changing or removing a key: the
// item's fields are replaced with what .env holds.
//
// Run from back-end/, signed in to the 1Password CLI (`op`):
//   npm run env:push
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { parse } from 'dotenv';

export const VAULT = 'Blogify Inc.';
export const ITEM = 'Blogify back-end env';

// The item as an `op item create/edit --template` JSON: one concealed field per key.
export function itemTemplate(env) {
  return {
    title: ITEM,
    category: 'SECURE_NOTE',
    fields: [
      {
        id: 'notesPlain',
        type: 'STRING',
        purpose: 'NOTES',
        value: 'Keys of back-end/.env. Written by `npm run env:push`; rebuild .env with `npm run env:pull`.',
      },
      ...Object.entries(env).map(([key, value]) => ({ id: key, label: key, type: 'CONCEALED', value })),
    ],
  };
}

// The .env.tpl text: the same keys, each pointing at its field in the item.
export function envTemplate(keys) {
  return [
    `# Generated by \`npm run env:push\` from the keys in .env. Holds no secrets.`,
    `# Rebuild .env from 1Password with \`npm run env:pull\`.`,
    ...keys.map(key => `${key}=op://${VAULT}/${ITEM}/${key}`),
    '',
  ].join('\n');
}

function op(args) {
  return spawnSync('op', args, { encoding: 'utf8' });
}

if (import.meta.main) {
  const env = parse(readFileSync('.env'));
  const keys = Object.keys(env);
  if (!keys.length) {
    console.error('.env has no keys.');
    process.exit(1);
  }

  // The values go through a private temp file rather than the command line,
  // where other processes could see them.
  const dir = mkdtempSync(join(tmpdir(), 'env-to-1password-'));
  const templatePath = join(dir, 'item.json');
  try {
    writeFileSync(templatePath, JSON.stringify(itemTemplate(env)), { mode: 0o600 });

    const exists = op(['item', 'get', ITEM, '--vault', VAULT, '--format', 'json']).status === 0;
    const result = exists
      ? op(['item', 'edit', ITEM, '--vault', VAULT, '--template', templatePath, '--format', 'json'])
      : op(['item', 'create', '--vault', VAULT, '--template', templatePath, '--format', 'json']);
    if (result.status !== 0) {
      console.error(result.stderr.trim());
      process.exit(1);
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }

  writeFileSync('.env.tpl', envTemplate(keys));
  // Key names only: the values aren't printed.
  console.log(`Saved ${keys.join(', ')} to "${ITEM}" in the ${VAULT} vault and updated .env.tpl.`);
}
