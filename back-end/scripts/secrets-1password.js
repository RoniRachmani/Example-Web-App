// Keeps the back end's gitignored secret files in 1Password, so a new machine
// can rebuild them with one command. Run from back-end/, signed in to the
// 1Password CLI (`op`):
//   npm run secrets:pull   # writes .env, prod-env.yaml and credentials.json
//   npm run secrets:push   # after changing any of them: updates 1Password and the .tpl files
//
// .env and prod-env.yaml are each kept as one item with a concealed field per
// key, and the committed .env.tpl and prod-env.yaml.tpl point at those fields.
// They are separate items so a key meant only for local development never
// reaches App Engine. credentials.json is kept as a document. A push replaces
// what 1Password holds with the local files, so a key removed locally is
// removed there too.
import { chmodSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { parse } from 'dotenv';

export const VAULT = 'Blogify Inc.';
export const ENV_ITEM = 'Blogify back-end env';
export const PROD_ENV_ITEM = 'Blogify back-end prod env';
export const CREDENTIALS_DOCUMENT = 'Blogify back-end credentials.json';

const FILES = ['.env', 'prod-env.yaml', 'credentials.json'];

function reference(item, key) {
  return `op://${VAULT}/${item}/${key}`;
}

// The item as an `op item create/edit --template` JSON: one concealed field per key.
export function itemTemplate(title, env) {
  return {
    title,
    category: 'SECURE_NOTE',
    fields: [
      {
        id: 'notesPlain',
        type: 'STRING',
        purpose: 'NOTES',
        value: 'Written by `npm run secrets:push` in back-end/; rebuild the file with `npm run secrets:pull`.',
      },
      ...Object.entries(env).map(([key, value]) => ({ id: key, label: key, type: 'CONCEALED', value })),
    ],
  };
}

const HEADER = [
  '# Generated by `npm run secrets:push`. Holds no secrets: each value points at 1Password.',
  '# Rebuild the real file with `npm run secrets:pull`.',
];

export function envTemplate(keys) {
  return [...HEADER, ...keys.map(key => `${key}=${reference(ENV_ITEM, key)}`), ''].join('\n');
}

// prod-env.yaml as app.yaml includes it: env_variables with one quoted value per key.
export function parseProdEnv(text) {
  const env = {};
  for (const line of text.split('\n')) {
    const match = line.match(/^\s+([A-Za-z_][A-Za-z0-9_]*):\s*(.*?)\s*$/);
    if (!match) continue;
    const value = match[2];
    env[match[1]] = value.startsWith('"') ? JSON.parse(value) : value.replace(/^'(.*)'$/, '$1');
  }
  return env;
}

export function prodEnvTemplate(keys) {
  return [
    ...HEADER,
    'env_variables:',
    ...keys.map(key => `  ${key}: "{{ ${reference(PROD_ENV_ITEM, key)} }}"`),
    '',
  ].join('\n');
}

function op(args) {
  const result = spawnSync('op', args, { encoding: 'utf8' });
  if (result.status !== 0) {
    console.error(result.stderr.trim());
    process.exit(1);
  }
  return result;
}

function exists(title) {
  return spawnSync('op', ['item', 'get', title, '--vault', VAULT, '--format', 'json']).status === 0;
}

// The values go through a private temp file rather than the command line,
// where other processes could see them.
function saveItem(title, env) {
  const dir = mkdtempSync(join(tmpdir(), 'secrets-1password-'));
  const templatePath = join(dir, 'item.json');
  try {
    writeFileSync(templatePath, JSON.stringify(itemTemplate(title, env)), { mode: 0o600 });
    op(exists(title)
      ? ['item', 'edit', title, '--vault', VAULT, '--template', templatePath]
      : ['item', 'create', '--vault', VAULT, '--template', templatePath]);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function push() {
  // Key names only: the values aren't printed.
  if (existsSync('.env')) {
    const env = parse(readFileSync('.env'));
    saveItem(ENV_ITEM, env);
    writeFileSync('.env.tpl', envTemplate(Object.keys(env)));
    console.log(`.env: saved ${Object.keys(env).join(', ')} to "${ENV_ITEM}".`);
  }

  if (existsSync('prod-env.yaml')) {
    const env = parseProdEnv(readFileSync('prod-env.yaml', 'utf8'));
    // The template puts each value inside double quotes, which these would break.
    const unsafe = Object.keys(env).filter(key => /["\\\n]/.test(env[key]));
    if (unsafe.length) {
      console.error(`prod-env.yaml: ${unsafe.join(', ')} contain a quote, backslash or newline, which prod-env.yaml.tpl can't hold.`);
      process.exit(1);
    }
    saveItem(PROD_ENV_ITEM, env);
    writeFileSync('prod-env.yaml.tpl', prodEnvTemplate(Object.keys(env)));
    console.log(`prod-env.yaml: saved ${Object.keys(env).join(', ')} to "${PROD_ENV_ITEM}".`);
  }

  if (existsSync('credentials.json')) {
    op(exists(CREDENTIALS_DOCUMENT)
      ? ['document', 'edit', CREDENTIALS_DOCUMENT, 'credentials.json', '--vault', VAULT]
      : ['document', 'create', 'credentials.json', '--title', CREDENTIALS_DOCUMENT, '--vault', VAULT]);
    console.log(`credentials.json: saved to "${CREDENTIALS_DOCUMENT}".`);
  }

  console.log(`All in the ${VAULT} vault. Commit any change to .env.tpl or prod-env.yaml.tpl.`);
}

function pull() {
  op(['inject', '--force', '-i', '.env.tpl', '-o', '.env']);
  op(['inject', '--force', '-i', 'prod-env.yaml.tpl', '-o', 'prod-env.yaml']);
  op(['document', 'get', CREDENTIALS_DOCUMENT, '--vault', VAULT, '--out-file', 'credentials.json', '--force']);
  for (const file of FILES) chmodSync(file, 0o600);
  console.log(`Wrote ${FILES.join(', ')} from the ${VAULT} vault.`);
}

if (import.meta.main) {
  const command = process.argv[2];
  if (command === 'push') push();
  else if (command === 'pull') pull();
  else {
    console.error('Usage: node scripts/secrets-1password.js push|pull');
    process.exit(1);
  }
}
